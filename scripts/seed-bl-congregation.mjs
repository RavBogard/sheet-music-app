#!/usr/bin/env node
/**
 * v11-05-04 — seed the Brothers Lazaroff per-org congregation doc (prod runner).
 *
 * v11-05-04 made the `config/congregation` singleton per-org via doc-id
 * namespacing (src/lib/org/registry.ts `congregationDocId`): crc keeps the BARE
 * `config/congregation` doc (zero migration); other orgs read
 * `config/congregation__{org}`. With no BL doc, BL surfaces gracefully fall back
 * to CRC-flavored DEFAULTS ("Central Reform Congregation"). This seeds
 * `config/congregation__brotherslazaroff` with BL's own identity so the BL app
 * chrome, print footer, and MCP get_congregation_context read "Brothers Lazaroff".
 *
 * Sibling of scripts/backfill-user-orgids.mjs — same auth path (.env.local SA
 * cert OR GOOGLE_APPLICATION_CREDENTIALS ADC), same DRY-RUN-by-default discipline.
 * Idempotent: if config/congregation__brotherslazaroff already exists it is
 * SKIPPED unless --force. The CRC doc is NEVER touched.
 * Rollback: delete config/congregation__brotherslazaroff (BL degrades to defaults).
 *
 * Usage:
 *   node scripts/seed-bl-congregation.mjs            # DRY-RUN (prints the doc it WOULD write)
 *   node scripts/seed-bl-congregation.mjs --apply    # real write
 *   node scripts/seed-bl-congregation.mjs --apply --force  # overwrite an existing doc
 *
 * Single-owner rule ([[feedback_single_owner_destructive_runs]]): inspect the
 * DRY-RUN report BEFORE --apply. Run at v11-05 phase close with the other backfills.
 */
import { initializeApp, cert, applicationDefault, getApps } from "firebase-admin/app"
import { getFirestore } from "firebase-admin/firestore"
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"

// ---------- .env.local loader (mirror backfill-user-orgids.mjs) ----------
const __dirname = dirname(fileURLToPath(import.meta.url))
const ENV_PATH = join(__dirname, "..", ".env.local")
{
    let envText
    try {
        envText = readFileSync(ENV_PATH, "utf8")
    } catch (err) {
        process.stderr.write(`!! Cannot read ${ENV_PATH}: ${err.message}\n`)
        process.exit(1)
    }
    for (const line of envText.split("\n")) {
        const m = line.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/)
        if (!m) continue
        let val = m[2]
        if (val.startsWith('"') && val.endsWith('"')) val = val.slice(1, -1)
        val = val.replace(/\\n/g, "\n")
        if (!(m[1] in process.env)) process.env[m[1]] = val
    }
}

const PROJECT_ID = process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || "crcmusiccharts"
const APPLY = process.argv.includes("--apply")
const FORCE = process.argv.includes("--force")

// Lockstep with src/lib/org/registry.ts congregationDocId('brotherslazaroff').
const BL_DOC_ID = "congregation__brotherslazaroff"

/**
 * Brothers Lazaroff congregation identity. Shape mirrors CongregationConfig
 * (src/lib/congregation-store.ts). themeColor matches getOrgBranding (#0a0e1a,
 * the BL navy from v11-03-02). NO scheduling.rabbiProfiles — a band has no
 * per-service rabbi. `features` mirrors the CRC defaults.
 */
const BL_CONGREGATION = {
    name: "Brothers Lazaroff",
    shortName: "Brothers Lazaroff",
    location: "St. Louis, MO",
    logoUrl: "",
    description: "Songs & setlists for the band",
    themeColor: "#0a0e1a",
    driveFolderId: "",
    features: {
        monitor: true,
        ai: true,
        audio: true,
        collaboration: true,
    },
    printFooter: "Generated by Brothers Lazaroff",
}

function initFirestore() {
    const email = process.env.FIREBASE_CLIENT_EMAIL
    const key = process.env.FIREBASE_PRIVATE_KEY
    if (getApps().length === 0) {
        if (email && key) {
            initializeApp({ credential: cert({ projectId: PROJECT_ID, clientEmail: email, privateKey: key }) })
        } else if (process.env.GOOGLE_APPLICATION_CREDENTIALS) {
            initializeApp({ credential: applicationDefault(), projectId: PROJECT_ID })
        } else {
            throw new Error(
                "No Admin credentials. Provide FIREBASE_CLIENT_EMAIL + FIREBASE_PRIVATE_KEY in .env.local, " +
                    "OR set GOOGLE_APPLICATION_CREDENTIALS to a service-account key JSON.",
            )
        }
    }
    return getFirestore()
}

async function main() {
    const db = initFirestore()
    process.stderr.write(`# seed-bl-congregation.mjs — mode=${APPLY ? "APPLY" : "DRY-RUN"}${FORCE ? " (force)" : ""}\n`)
    process.stderr.write(`# project=${PROJECT_ID}\n# doc=config/${BL_DOC_ID}\n# started=${new Date().toISOString()}\n\n`)

    const ref = db.collection("config").doc(BL_DOC_ID)
    const existing = await ref.get()
    const report = { docId: BL_DOC_ID, existed: existing.exists, wrote: false, skipped: false }

    if (existing.exists && !FORCE) {
        report.skipped = true
        process.stderr.write(`  doc already exists — SKIPPING (pass --force to overwrite)\n`)
        process.stderr.write(`  current: ${JSON.stringify(existing.data())}\n`)
    } else if (!APPLY) {
        process.stderr.write(`  would write config/${BL_DOC_ID}:\n`)
        process.stderr.write(`  ${JSON.stringify(BL_CONGREGATION, null, 2)}\n`)
    } else {
        await ref.set(BL_CONGREGATION, { merge: true })
        report.wrote = true
        process.stderr.write(`  wrote config/${BL_DOC_ID}\n`)
    }

    const summary = {
        mode: APPLY ? "apply" : "dry-run",
        projectId: PROJECT_ID,
        startedAt: new Date().toISOString(),
        report,
    }
    process.stderr.write(`\n=== Summary (${summary.mode}) ===\n`)
    process.stdout.write(JSON.stringify({ summary }, null, 2) + "\n")
}

main().catch((err) => {
    process.stderr.write(`\n!! FATAL: ${err.stack || err.message}\n`)
    process.exit(1)
})
