import { afterEach, beforeEach, describe, expect, it, vi } from "vitest"

import { clearPrimedOrgConfigs } from "@/lib/org/config-cache"
import { primeTestOrg } from "@/lib/org/__tests__/test-org-config"

/**
 * Multi-tenant phase 1 golden — the congregation defaults: the client
 * congregation store's DEFAULT_CONFIG and the MCP get_congregation_context
 * fallback. Both tenants see CRC's values today (BL frozen).
 */
vi.mock("@/lib/firebase", () => ({ auth: {}, subscribeWithDb: vi.fn(() => () => {}) }))
vi.mock("firebase/auth", () => ({ onAuthStateChanged: vi.fn(() => () => {}) }))
vi.mock("@/lib/firebase-admin", async () => (await import("./tenant-mocks")).firebaseAdminMock())
vi.mock("@/lib/server-auth", () => ({ getServerCongregationConfig: vi.fn(async () => null) }))
vi.mock("@/lib/server-setlists", () => ({ getAllSetlists: vi.fn(async () => []) }))

const CRC_STORE_DEFAULT = {
    name: "Central Reform Congregation",
    shortName: "CRC Music",
    location: "St. Louis, MO",
    logoUrl: "/logo.jpg",
    description: "Digital Sheet Music Library for CRC Musicians",
    themeColor: "#7c3aed",
    driveFolderId: "",
    // Phase 6 removed `features` (monitor/ai/audio/collaboration): the flags
    // moved to the tenant config. Nothing rendered from ai/audio/collaboration.
    printFooter: "Generated by CRC Music Books • a project of Rabbi Daniel Bogard",
}

const CRC_MCP_DEFAULT = {
    name: "Central Reform Congregation",
    shortName: "CRC Music",
    location: "St. Louis, MO",
    description: "Digital Sheet Music Library for CRC Musicians",
}

async function storeDefault(dataOrg: string | undefined) {
    if (dataOrg === undefined) delete document.documentElement.dataset.org
    else document.documentElement.dataset.org = dataOrg
    vi.resetModules()
    const { useCongregationStore } = await import("@/lib/congregation-store")
    return useCongregationStore.getState().config
}

async function mcpDefault(org: string) {
    const { getCongregationContext } = await import("@/lib/mcp/tools/congregation")
    const out = (await getCongregationContext("u-1", {}, org)) as { congregation: Record<string, unknown> }
    const { name, shortName, location, description, usingDefaults } = out.congregation
    expect(usingDefaults).toBe(true)
    return { name, shortName, location, description }
}

describe("multi-tenant P1 golden: congregation defaults", () => {
    beforeEach(() => {
        clearPrimedOrgConfigs()
        localStorage.clear()
    })
    afterEach(() => {
        delete document.documentElement.dataset.org
    })

    for (const org of ["crc", "brotherslazaroff", undefined]) {
        it(`client store default (data-org=${org})`, async () => {
            expect(await storeDefault(org)).toEqual(CRC_STORE_DEFAULT)
        })
    }

    for (const org of ["crc", "brotherslazaroff"]) {
        it(`MCP get_congregation_context fallback (${org})`, async () => {
            expect(await mcpDefault(org)).toEqual(CRC_MCP_DEFAULT)
        })
    }
})

describe("multi-tenant P1: congregation defaults follow the tenant", () => {
    beforeEach(() => {
        clearPrimedOrgConfigs()
        localStorage.clear()
    })
    afterEach(() => {
        delete document.documentElement.dataset.org
    })

    it("client store default for testshul", async () => {
        document.documentElement.dataset.org = "testshul"
        vi.resetModules()
        const { primeTestOrg: prime } = await import("@/lib/org/__tests__/test-org-config")
        prime()
        const { useCongregationStore } = await import("@/lib/congregation-store")
        expect(useCongregationStore.getState().config).toEqual({
            ...CRC_STORE_DEFAULT,
            name: "Test Shul Tehila",
            shortName: "Test Shul Music",
            location: "Jerusalem",
            logoUrl: "",
            description: "Charts for Test Shul Tehila",
            themeColor: "#123456",
            printFooter: "Generated by Test Shul Music Books • a project of Rabbi Daniel Bogard",
        })
    })

    it("client store re-applies the tenant defaults on init once the config is primed", async () => {
        document.documentElement.dataset.org = "testshul"
        vi.resetModules()
        const { useCongregationStore } = await import("@/lib/congregation-store")
        // Not primed at module load → CRC fallback.
        expect(useCongregationStore.getState().config.name).toBe("Central Reform Congregation")
        const { primeTestOrg: prime } = await import("@/lib/org/__tests__/test-org-config")
        prime()
        const stop = useCongregationStore.getState().init()
        expect(useCongregationStore.getState().config.name).toBe("Test Shul Tehila")
        stop()
    })

    it("MCP get_congregation_context fallback for testshul", async () => {
        primeTestOrg()
        expect(await mcpDefault("testshul")).toEqual({
            name: "Test Shul Tehila",
            shortName: "Test Shul Music",
            location: "Jerusalem",
            description: "Charts for Test Shul Tehila",
        })
    })
})
