describe("multi-tenant P1: code-table configs reproduce today's strings", () => {
    beforeEach(() => clearPrimedOrgConfigs())

    it("both code configs validate against the schema", () => {
        for (const id of ["crc", "brotherslazaroff"]) {
            expect(OrgConfigSchema.safeParse(codeOrgConfig(id)).success).toBe(true)
        }
    })

    it("the catalogue and the golden cover the same keys", () => {
        expect(Object.keys(CRC_LITERALS).sort()).toEqual(Object.keys(STRING_BASE).sort())
    })

    for (const key of Object.keys(CRC_LITERALS) as StringKey[]) {
        it(`crc ${key}`, () => {
            expect(orgString("crc", key)).toBe(CRC_LITERALS[key])
        })
        it(`brotherslazaroff ${key}`, () => {
            expect(orgString("brotherslazaroff", key)).toBe(BL_VOCAB_LITERALS[key] ?? CRC_LITERALS[key])
        })
    }

    it("every non-vocab key is frozen for BL", () => {
        const vocab = new Set(Object.keys(BL_VOCAB_LITERALS))
        const nonVocab = (Object.keys(STRING_BASE) as StringKey[]).filter((k) => !vocab.has(k))
        expect([...BL_FROZEN_CRC_KEYS].sort()).toEqual(nonVocab.sort())
    })

    it("an unknown org has no code config", () => {
        expect(codeOrgConfig("nava-tehila")).toBeNull()
    })
})
