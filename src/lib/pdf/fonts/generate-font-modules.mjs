// Regenerates the base64 font modules beside this script from the vendored
// TTFs. Run once after replacing a TTF:
//   node src/lib/pdf/fonts/generate-font-modules.mjs
//
// Why base64 modules instead of fs.readFileSync: the service sheet renders in
// the /api/mcp serverless function. An `import()`ed module is traced and
// bundled by Next.js with no next.config `outputFileTracingIncludes` entry,
// and dynamic import keeps the ~120 KB string out of English-only renders.
import { readFileSync, writeFileSync } from "node:fs"
import { createHash } from "node:crypto"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const FONTS = [
    { ttf: "Alef-Regular.ttf", out: "alef-regular.ts", name: "ALEF_REGULAR_B64" },
    { ttf: "Alef-Bold.ttf", out: "alef-bold.ts", name: "ALEF_BOLD_B64" },
]

for (const { ttf, out, name } of FONTS) {
    const bytes = readFileSync(join(here, ttf))
    const sha = createHash("sha256").update(bytes).digest("hex")
    const src =
        `// GENERATED by generate-font-modules.mjs from ${ttf} — do not edit.\n` +
        `// Alef, (c) 2012 HaGilda & Mushon Zer-Aviv, SIL Open Font License 1.1 (see OFL.txt).\n` +
        `// ${bytes.length} bytes, sha256 ${sha}\n` +
        `export const ${name} =\n    "${bytes.toString("base64")}"\n`
    writeFileSync(join(here, out), src)
    console.log(`${out}: ${bytes.length} bytes -> ${src.length} chars`)
}
