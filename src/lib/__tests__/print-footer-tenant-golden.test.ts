// ── Drawn-text reader (same apparatus as print-pipeline-omit-cover.test.ts) ──
function unescapeLiteral(s: string): string {
    return s.replace(/\\([nrtbf()\\])/g, (_, c) =>
        ({ n: "\n", r: "\r", t: "\t", b: "\b", f: "\f" } as Record<string, string>)[c] ?? c,
    )
}
function hexToText(hex: string): string {
    const x = hex.replace(/\s+/g, "")
    let out = ""
    for (let i = 0; i + 1 < x.length; i += 2) out += String.fromCharCode(parseInt(x.slice(i, i + 2), 16))
    return out
}
const TEXT_RE = /<([0-9A-Fa-f\s]*)>\s*Tj|\(((?:\\.|[^\\)])*)\)\s*Tj/g
function drawnStrings(content: string): string[] {
    const out: string[] = []
    TEXT_RE.lastIndex = 0
    let m: RegExpExecArray | null
    while ((m = TEXT_RE.exec(content)) !== null) {
        if (m[1] !== undefined) out.push(hexToText(m[1]))
        else if (m[2] !== undefined) out.push(unescapeLiteral(m[2]))
    }
    return out
}
function pageStream(doc: PDFDocument, pageIndex: number): string {
    const parts: string[] = []
    const push = (obj: unknown) => {
        if (!(obj instanceof PDFRawStream)) return
        const bytes = obj.getContents()
        let decoded: Buffer
        try {
            decoded = inflateSync(Buffer.from(bytes))
        } catch {
            decoded = Buffer.from(bytes)
        }
        parts.push(decoded.toString("latin1"))
    }
    const contents = doc.context.lookup(doc.getPage(pageIndex).node.get(PDFName.of("Contents")))
    if (contents instanceof PDFArray) {
        for (let i = 0; i < contents.size(); i++) push(doc.context.lookup(contents.get(i)))
    } else {
        push(contents)
    }
    return parts.join("\n")
}

const req = (org?: string): PrintRequest => ({
    title: "Friday Night Set",
    date: "Friday, March 13, 2026",
    coverOnly: true,
    tracks: [{ title: "Song One", key: "G", notes: "", fileId: "f1", type: "song" } as PrintRequest["tracks"][number]],
    ...(org ? { org } : {}),
})

/** The footer line drawn on the cover page (the one carrying the song count). */
async function coverFooter(org?: string): Promise<string> {
    const res = await generatePrintPdf(req(org))
    const doc = await PDFDocument.load(res.pdf)
    const strings = drawnStrings(pageStream(doc, 0))
    const footer = strings.filter((s) => s.startsWith("1 song"))
    expect(footer).toHaveLength(1)
    return footer[0]
}

const GOLDEN_FOOTER = "1 song · Generated by CRC Music Books · a project of Rabbi Daniel Bogard"

beforeEach(() => {
    h.congregationDocs = {}
    h.docIdsRead = []
    clearPrimedOrgConfigs()
})

describe("golden: print cover footer", () => {
    it("golden no org (crc)", async () => {
        expect(await coverFooter()).toBe(GOLDEN_FOOTER)
        expect(h.docIdsRead).toEqual(["congregation"])
    })
    it("golden crc", async () => {
        expect(await coverFooter("crc")).toBe(GOLDEN_FOOTER)
    })
    it("golden brotherslazaroff without its own doc (frozen CRC footer)", async () => {
        expect(await coverFooter("brotherslazaroff")).toBe(GOLDEN_FOOTER)
        expect(h.docIdsRead).toEqual(["congregation__brotherslazaroff"])
    })
    it("golden per-org doc printFooter still overrides", async () => {
        h.congregationDocs["congregation__brotherslazaroff"] = { printFooter: "Brothers Lazaroff band book" }
        expect(await coverFooter("brotherslazaroff")).toBe("1 song · Brothers Lazaroff band book")
    })
})
